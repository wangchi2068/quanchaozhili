/**
 * 三幕主线大纲——导演层的地基。
 * 设计原则：主线是"软骨架"，只提供方向与事件钩子，绝不强制剧情。
 * 推进靠规则（关键词命中 + 回合数门槛），保证模型自由发挥的同时主线不漂。
 */

export interface Phase {
  id: string;
  act: 1 | 2 | 3;
  title: string;
  /** 注入 system 的阶段指引（模型据此知道当前该往哪使劲） */
  summary: string;
  /** 当前阶段的目标清单 */
  objectives: string[];
  /** 任一关键词出现在最近剧情文本中即视为满足推进条件 */
  unlockKeywords: string[];
  /** 至少经过的回合数（防过早推进） */
  minTurns: number;
  /**
   * 本幕至少停留的回合数（按"进入本幕后的回合数"算，与全局累计的 minTurns 不同）。
   * 用于「这一幕必须慢慢演」的场合：只靠 minTurns 的话，玩家在前几幕多聊几句
   * 就会让全局计数提前达标，导致本幕一进来就被推走。
   */
  minTurnsInPhase?: number;
  /**
   * 强制推进：忽略 unlockKeywords，只要回合数达标（且满足防连跳间隔）就推进到下一幕。
   * 用于「不可回避的主线锚点」——例如玩家可能不会主动选择的悲剧转折。
   * 注意：本幕若同时设了 codaKeywords，收束闸门优先——autoAdvance 退化为超时兜底。
   */
  autoAdvance?: boolean;
  /**
   * 收束闸门：本幕必须等到这些词之一真的出现在剧情里，才允许翻到下一幕。
   * 用处——把「这一幕必须以某句话/某个画面收尾」从"提示词碰运气"变成硬条件：
   * 第五幕的落点是提米那句「我他妈都许了什么愿啊」，那就得等这句话真的写出来，
   * 否则一幕可以演完灾难就直接翻页，把落点整段丢掉。
   * 与 autoAdvance 并存时，autoAdvance 只作为超时兜底（见 codaGrace），不再无条件跳过。
   */
  codaKeywords?: string[];
  /** 收束闸门的兜底宽限（回合）：本幕停留超过 minTurnsInPhase + codaGrace 仍未命中时强推，防卡死。默认 2 */
  codaGrace?: number;
  /** 刚推进到本阶段时，注入一次的事件钩子（把剧情推向下一幕） */
  eventHint?: string;
  /** 本幕情绪基调（导演注入 system，防平铺流水账） */
  mood?: string;
  /** 本幕张力（1-10，注入后模型据此把握节奏） */
  tension?: number;
  /** 本幕节奏要点（可选，如"开场给虚假安全感 → 中段揭露背叛 → 结尾逼玩家选择"） */
  beats?: string[];
  /** 本幕必发生事件（原著锚点）：模型推进时须按序落实，防自创架空线 */
  mustEvents?: string[];
}

